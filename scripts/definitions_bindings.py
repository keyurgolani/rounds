#!/usr/bin/env python3
"""Generates the Python and TypeScript bindings for contracts/definitions/
(ROUNDS-00A-L02).

Each schema becomes a module of types: Python TypedDicts under
``backend/app/contracts/definitions/`` and TypeScript types under
``frontend/src/contracts/definitions/``. The schemas are the source of
truth; ``--check`` exits 1 when a committed binding has drifted from them,
which CI runs through backend/tests/test_definition_contracts.py.

TODO(ROUNDS-34-L08): #182's contracts package takes over generation and
keeps these output paths.

usage: definitions_bindings.py [--check]
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "contracts" / "definitions"
PY_DIR = ROOT / "backend" / "app" / "contracts" / "definitions"
TS_DIR = ROOT / "frontend" / "src" / "contracts" / "definitions"

# (schema file, module name, root type name)
SCHEMAS = (
    ("test-definition.v1.schema.json", "test_definition", "TestDefinitionV1"),
    ("harness-revision.v1.schema.json", "harness_revision", "HarnessRevisionV1"),
    ("artifact-renderer.v1.schema.json", "artifact_renderer", "ArtifactRendererV1"),
    ("render-request.v1.schema.json", "render_request", "RenderRequestV1"),
    ("resource-profile.v1.schema.json", "resource_profile", "ResourceProfileV1"),
    ("manifest.v1.schema.json", "manifest", "DefinitionsManifestV1"),
)
HEADER = "Generated by scripts/definitions_bindings.py from contracts/definitions/{file}. Do not edit."


def pascal(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", text) if part)


def _literal(value: Any) -> tuple[str, str]:
    return repr(value) if not isinstance(value, bool) else str(value), json.dumps(value)


class Module:
    """One schema's types, emitted in dependency order."""

    def __init__(self, schema: dict[str, Any], root: str) -> None:
        self.schema = schema
        self.root = root
        self.defs = schema.get("$defs", {})
        self.py: list[str] = []
        self.ts: list[str] = []
        self.done: dict[str, str] = {}

    def build(self) -> None:
        self.named(self.schema, self.root)

    def named(self, node: Any, name: str) -> tuple[str, str]:
        """Declares ``node`` as ``name`` when it needs a declaration."""
        if name in self.done:
            return name, name
        py, ts, decl = self.expr(node, name)
        if decl:
            return py, ts
        self.done[name] = name
        doc = node.get("description") if isinstance(node, dict) else None
        self.py.append(f"{name} = {py}\n" if not doc else f"{name} = {py}\n\"\"\"{_py_doc(doc)}\"\"\"\n")
        self.ts.append(_ts_doc(doc) + f"export type {name} = {ts};\n")
        return name, name

    def ref(self, ref: str) -> tuple[str, str]:
        key = ref.rsplit("/", 1)[-1]
        name = self.root + pascal(key)
        if name not in self.done:
            self.named(self.defs[key], name)
        return name, name

    def expr(self, node: Any, hint: str) -> tuple[str, str, bool]:
        """(python, typescript, declared): declared means expr already
        emitted ``hint`` as a named object."""
        if node is True or node == {}:
            return "Any", "unknown", False
        if not isinstance(node, dict):
            raise ValueError(f"unsupported schema node for {hint}")
        if "$ref" in node:
            py, ts = self.ref(node["$ref"])
            return py, ts, False
        if "const" in node:
            py, ts = _literal(node["const"])
            return f"Literal[{py}]", ts, False
        if "enum" in node:
            pys, tss = zip(*(_literal(v) for v in node["enum"]))
            return f"Literal[{', '.join(pys)}]", " | ".join(tss), False
        for key in ("oneOf", "anyOf"):
            if key in node:
                parts = [self.expr(sub, _branch_name(hint, sub, i))[:2] for i, sub in enumerate(node[key])]
                return " | ".join(p for p, _ in parts), " | ".join(t for _, t in parts), False
        kind = node.get("type")
        if isinstance(kind, list):
            parts = [self.expr({**node, "type": k}, hint)[:2] for k in kind]
            return " | ".join(p for p, _ in parts), " | ".join(t for _, t in parts), False
        if kind == "object":
            self.object(node, hint)
            return hint, hint, True
        if kind == "array":
            item = node.get("items", True)
            py, ts, _ = self.expr(item, hint + "Item")
            return f"list[{py}]", f"Array<{ts}>" if " | " in ts else f"{ts}[]", False
        scalars = {"string": ("str", "string"), "integer": ("int", "number"), "number": ("float", "number"),
                   "boolean": ("bool", "boolean"), "null": ("None", "null")}
        if kind in scalars:
            py, ts = scalars[kind]
            return py, ts, False
        raise ValueError(f"unsupported schema node for {hint}: {sorted(node)}")

    def object(self, node: dict[str, Any], name: str) -> None:
        if name in self.done:
            return
        required = set(node.get("required", []))
        fields_py: list[str] = []
        fields_ts: list[str] = []
        for key, sub in node.get("properties", {}).items():
            py, ts, _ = self.expr(sub, name + pascal(key))
            fields_py.append(f"        {key!r}: {py if key in required else f'NotRequired[{py}]'},")
            prop = key if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", key) else json.dumps(key)
            doc = sub.get("description") if isinstance(sub, dict) else None
            fields_ts.append(_ts_doc(doc, "  ") + f"  {prop}{'' if key in required else '?'}: {ts};")
        self.done[name] = name
        doc = node.get("description")
        body = "\n".join(fields_py)
        self.py.append(f"{name} = TypedDict(\n    {name!r},\n    {{\n{body}\n    }},\n)\n"
                       + (f"\"\"\"{_py_doc(doc)}\"\"\"\n" if doc else ""))
        self.ts.append(_ts_doc(doc) + f"export interface {name} {{\n" + "\n".join(fields_ts) + "\n}\n")


def _branch_name(hint: str, branch: Any, index: int) -> str:
    """A oneOf branch's type name: from the constant that tells it apart,
    or its one required key, else its position."""
    if isinstance(branch, dict) and branch.get("type") == "object":
        for prop in (branch.get("properties") or {}).values():
            if isinstance(prop, dict) and isinstance(prop.get("const"), str):
                return hint + pascal(prop["const"])
        required = branch.get("required") or []
        if len(required) == 1:
            return hint + pascal(required[0])
    return f"{hint}{index}"


def _py_doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _ts_doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    return f"{indent}/** {text.replace('*/', '* /')} */\n"


def render(file: str, module: str, root: str) -> tuple[str, str]:
    schema = json.loads((SCHEMA_DIR / file).read_text(encoding="utf-8"))
    mod = Module(schema, root)
    mod.build()
    header = HEADER.format(file=file)
    py = (
        f'"""{header}"""\n'
        "from __future__ import annotations\n\n"
        "from typing import Any, Literal, NotRequired, TypedDict\n\n"
        "__all__ = [" + ", ".join(repr(n) for n in mod.done) + "]\n\n\n"
        + "\n\n".join(mod.py)
    )
    if "Any" not in "".join(mod.py):
        py = py.replace("from typing import Any, Literal", "from typing import Literal")
    if "NotRequired[" not in py:
        py = py.replace("Literal, NotRequired, TypedDict", "Literal, TypedDict")
    ts = f"// {header}\n\n" + "\n".join(mod.ts)
    return py, ts


def outputs() -> dict[Path, str]:
    out: dict[Path, str] = {}
    exports: list[str] = []
    for file, module, root in SCHEMAS:
        py, ts = render(file, module, root)
        out[PY_DIR / f"{module}.py"] = py
        out[TS_DIR / f"{module}.ts"] = ts
        exports.append(f"export * from './{module}';\n")
    out[PY_DIR / "__init__.py"] = '"""Bindings for contracts/definitions/, from scripts/definitions_bindings.py."""\n'
    out[PY_DIR.parent / "__init__.py"] = '"""Generated contract bindings (ROUNDS-00A-L02)."""\n'
    out[TS_DIR / "index.ts"] = "// Generated by scripts/definitions_bindings.py. Do not edit.\n\n" + "".join(exports)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed binding differs")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"stale: {path} (run python3 scripts/definitions_bindings.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
