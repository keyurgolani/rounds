// Generated privacy docs (ROUNDS-14-L01): docs/privacy-retention.md in full,
// and the settings section of docs/configuration.md between its markers.
// Both come from contracts/privacy/, so the docs match the enforced numbers.

import { CONFIG_BEGIN, CONFIG_END, DOC_PATH } from './files.mjs';

const esc = (s) => String(s).replace(/\|/g, '\\|');
const row = (cells) => `| ${cells.map(esc).join(' | ')} |`;
const sep = (n) => `| ${Array(n).fill('---').join(' | ')} |`;
const code = (s) => `\`${s}\``;

export function describeRule(rule) {
  const obl = (o) => (o.length ? ` (${o.join(', ')})` : '');
  if (rule.decision === 'deny') return `deny ${rule.code}`;
  if (rule.decision === 'allow') return `allow${obl(rule.obligations)}`;
  if (rule.decision === 'allow-with-consent') return `allow with ${rule.consent} consent${obl(rule.obligations)}, else ${rule.otherwise}`;
  const cases = rule.cases.map((c) => `${Object.entries(c.when).map(([k, v]) => `${k} ${v}`).join(' and ')}${obl(c.obligations)}`);
  return `allow if ${cases.join('; or ')}, else ${rule.otherwise}`;
}

function retentionText(spec) {
  if (!spec) return 'as its row';
  const days = (v) => (Number.isInteger(v) ? `${v} days` : v);
  const allowed = spec.range ? `${spec.range[0]} to ${spec.range[1]} days` : spec.choices.map(days).join(', ');
  return [`default ${days(spec.default)}`, `allowed ${allowed}`, spec.setting ? `set by ${code(spec.setting)}` : `set by the ${spec.setBy}`].join('; ');
}

export function renderPrivacyDoc(P, extra = {}) {
  const policy = P.policy;
  const out = [];
  const versions = policy.versions.map((v) => code(`${v.id}@${v.current}`)).join(', ');
  out.push('# Privacy and retention', '');
  out.push(`Generated by ${code('node scripts/conformance/run.mjs --write')} from ${code('contracts/privacy/')} (ROUNDS-14-L01, ${policy.decisionRecord}). Edit the policy files, not this page.`, '');
  out.push(`Policy versions: ${versions}. Anything the policy doesn't allow is denied, and packs, flags, operators, and users may only tighten it. ${policy.spec.packRule}`, '');
  out.push(`Policies fail closed for: ${policy.spec.failClosed.join(', ')}.`, '');
  out.push('## Classes and sinks', '');
  out.push('The spec\'s matrix, word for word:', '');
  out.push(row(policy.matrix.columns), sep(policy.matrix.columns.length));
  for (const r of policy.matrix.rows) out.push(row(r.cells));
  out.push('', 'What the evaluators decide for each class and sink:', '');
  const sinks = policy.sinks.filter((s) => s.families.includes('class'));
  out.push(row(['Class', ...sinks.map((s) => s.id)]), sep(sinks.length + 1));
  for (const cls of policy.classes) {
    out.push(row([cls.name, ...sinks.map((s) => describeRule(policy.matrix.cells.find((c) => c.class === cls.name && c.sink === s.id).rule))]));
  }
  out.push('', 'Platform content takes a visibility instead of a class:', '');
  const vsinks = policy.sinks.filter((s) => s.families.includes('visibility'));
  out.push(row(['Visibility', ...vsinks.map((s) => s.id)]), sep(vsinks.length + 1));
  for (const v of policy.visibilities) {
    out.push(row([v.name, ...vsinks.map((s) => describeRule(policy.visibilityRules.find((r) => r.visibility === v.name && r.sink === s.id).rule))]));
  }
  out.push('', 'Each sink\'s enforcing leaf:', '');
  out.push(row(['Sink', 'Enforced by']), sep(2));
  for (const s of policy.sinks) out.push(row([s.id, s.enforcingLeaf]));
  out.push('', '## Lifecycle', '', 'The spec\'s lifecycle table, word for word:', '');
  out.push(row(policy.lifecycle.columns), sep(policy.lifecycle.columns.length));
  for (const r of policy.lifecycle.rows) out.push(row(r.cells));
  out.push('', 'The numbers the evaluators enforce:', '');
  out.push(row(['Row', 'Retention', 'Purge within', 'Enforced by']), sep(4));
  for (const r of policy.lifecycle.rows) out.push(row([r.id, retentionText(r.retention), `${r.purgeWithinHours} hours`, r.enforcement.map((e) => e.leaf).join(', ')]));
  for (const r of policy.lifecycle.decided) out.push(row([r.id, r.sameAs ? `as ${r.sameAs}` : retentionText(r.retention), r.sameAs ? `as ${r.sameAs}` : `${r.purgeWithinHours} hours`, r.enforcement.map((e) => e.leaf).join(', ')]));
  out.push('', 'Decided here:', '');
  for (const r of policy.lifecycle.decided) out.push(`- ${r.category}: ${r.decision}`);
  out.push('', `Account deletion: ${policy.accountDeletion.text}`, '');
  out.push('## Locations', '');
  out.push(`A destination's location comes from ${policy.locations.decidedFrom}.`, '');
  for (const c of policy.locations.classes) out.push(`- ${code(c.id)}: ${c.meaning}.`);
  const never = policy.locations.never;
  out.push('', `Never destinations, which get no location class: loopback (${never.loopback.join(', ')}), link-local (${never.linkLocal.join(', ')}), unspecified (${never.unspecified.join(', ')}), the metadata addresses (${never.metadata.join(', ')}), single-label host names, the service names ${never.serviceNames.map(code).join(', ')}, and names ending ${never.serviceSuffixes.map(code).join(', ')}.`, '');
  out.push(`Other non-public ranges, which get no location class either: ${policy.locations.nonPublic.join(', ')}.`, '');
  out.push(`An IPv6 address inside ${policy.locations.unwrap.join(', ')} is judged as the IPv4 address that follows the prefix.`, '');
  out.push(`Private networks: ${policy.locations.privateNetworks.join(', ')}. ${policy.locations.combination}`, '');
  out.push('## Credential channel', '', `${policy.credentialChannel.rule} It goes in the ${policy.credentialChannel.headers.map(code).join(' or ')} header, matched by ${policy.credentialChannel.match}.`, '');
  out.push('## Consent', '');
  for (const u of policy.consent.units) out.push(`- ${code(u.id)}: ${u.meaning}`);
  out.push('', `Consent is never standing. A batch preview may list up to ${policy.consent.batchMax} calls.`, '');
  out.push('## Redaction', '');
  for (const o of policy.redaction.operators) out.push(`- ${code(o.id)}: ${o.meaning}`);
  out.push('', '## Operator settings', '', 'The runner validates these at startup; see [configuration](configuration.md#privacy-and-retention-settings).', '');
  out.push(row(['Variable', 'What it sets']), sep(2));
  for (const s of policy.operatorSettings) out.push(row([code(s.name), s.meaning]));
  if (P.purposes) {
    out.push('', '## Purposes', '', 'Every purpose that calls an AI provider. The scan fails CI on a provider call from a function no purpose names.', '');
    out.push(row(['Purpose', 'Status', 'Consent', 'Classes', 'Owner', 'Manual path']), sep(6));
    for (const p of P.purposes.purposes) out.push(row([code(p.id), p.status, p.consent, p.classes.join(', ') || 'none', p.owner, p.manualPath]));
  }
  if (P.violations) {
    out.push('', '## Violation register', '');
    const open = P.violations.entries.filter((v) => v.status === 'open');
    const byOwner = new Map();
    for (const v of open) byOwner.set(v.owner, [...(byOwner.get(v.owner) || []), v]);
    out.push(`${open.length} open, ${P.violations.entries.length - open.length} closed.`, '');
    out.push(row(['Entry', 'Status', 'Breach', 'Owner', 'Exit']), sep(5));
    for (const v of P.violations.entries) out.push(row([String(v.id), v.status === 'closed' ? `closed (${v.history.map((h) => `#${h.pr}`).join(', ')})` : 'open', v.summary, v.owner, v.exit]));
  }
  out.push('', '## Enforcement still pending', '', 'Each row owner\'s tests read the policy value; until a test cites its row, the row is pending here.', '');
  for (const line of pendingEnforcement(policy)) out.push(`- ${line}`);
  if (extra.fieldCount !== undefined) out.push('', `The field map classifies ${extra.fieldCount} ids.`);
  out.push('');
  return `${out.join('\n')}`;
}

export function pendingEnforcement(policy) {
  const out = [];
  const add = (what, list) => { const pending = (list || []).filter((e) => !e.test).map((e) => e.leaf); if (pending.length) out.push(`${what}: ${pending.join(', ')}`); };
  for (const r of [...policy.lifecycle.rows, ...policy.lifecycle.decided]) add(`lifecycle ${r.id}`, r.enforcement);
  for (const b of ['accountDeletion', 'locations', 'credentialChannel', 'consent', 'redaction']) add(b, policy[b].enforcement);
  return out;
}

export function renderConfigSection(P, settings) {
  const policy = P.policy;
  const out = [CONFIG_BEGIN, '## Privacy And Retention Settings', ''];
  out.push(`The runner reads these once at startup and refuses to start on a bad value, naming the setting and its bounds, or the position of the entry it refuses. The message never repeats a day count, and shows an entry's network only once it has parsed as one. Unset or empty takes the default. On Kubernetes, set them in the ${code('rounds-runner-secrets')} Secret: the runner's manifest leaves them out of ${code('env')}, where a value would hide the Secret's. The bounds come from ${code('contracts/privacy/policy.json')}; see [privacy and retention](${DOC_PATH.replace('docs/', '')}).`, '');
  out.push(row(['Variable', 'Allowed', 'Default', 'What it sets']), sep(4));
  for (const s of settings) out.push(row([code(s.name), s.allowed, s.default, s.meaning]));
  out.push('');
  out.push(`${code('ROUNDS_AI_PRIVATE_ENDPOINTS')} lists the AI endpoints on your own network. Each entry is ${code('ip:port')}, ${code('[ipv6]:port')}, ${code('cidr:port')}, or ${code('[ipv6-cidr]:port')}, inside ${policy.locations.privateNetworks.join(', ')}. An entry that names a host, or names or covers loopback, link-local, a metadata address, or a service name such as ${code('pocketbase')}, stops the runner. ${policy.locations.combination}`, '');
  const readers = policy.operatorSettings.map((s) => {
    const row = [...policy.lifecycle.rows, ...policy.lifecycle.decided].find((r) => r.id === s.row);
    return `${code(s.name)} by ${s.readAtDispatchBy || row?.enforcement.map((e) => e.leaf).join(' and ')}`;
  });
  out.push(`Today the runner only validates these. The values take effect when their enforcing leaves land: ${readers.join(', ')}. Until then the private-network gate alone decides which private addresses a provider may use, as before.`, '');
  out.push(CONFIG_END);
  return out.join('\n');
}

export function spliceConfig(text, section) {
  const start = text.indexOf(CONFIG_BEGIN);
  const end = text.indexOf(CONFIG_END);
  if (start === -1 || end === -1 || end < start) return null;
  return `${text.slice(0, start)}${section}${text.slice(end + CONFIG_END.length)}`;
}
