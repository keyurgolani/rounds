// The privacy policy's files (ROUNDS-14-L01) and the copies each image
// builds from. contracts/privacy/ is the source; run.mjs --write copies it
// byte for byte into backend/app/privacy/ and frontend/src/privacy/, and a
// plain run fails CONFORMANCE_DRIFT when a copy differs.
// TODO(ROUNDS-34-L08): the shared contracts package replaces the copies.

