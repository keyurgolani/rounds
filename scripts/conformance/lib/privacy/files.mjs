// The files contracts/privacy/ holds, in a stable order.
export function sourceFiles(ctx) {
  return ctx.files().filter((f) => f.startsWith(`${PRIVACY_DIR}/`) && f.endsWith('.json')).sort();
}

// [{ path, content }] for every copy.
export function copies(ctx) {
  const out = [];
  for (const file of sourceFiles(ctx)) {
    const rel = file.slice(PRIVACY_DIR.length + 1);
    const content = ctx.read(file);
    for (const dir of COPY_DIRS) out.push({ path: path.posix.join(dir, rel), content });
  }
  return out;
}

// Copies that exist but no longer have a source, so a removed vector
// doesn't linger in an image.
export function staleCopies(ctx) {
  const wanted = new Set(copies(ctx).map((c) => c.path));
  return ctx.files().filter((f) => COPY_DIRS.some((d) => f.startsWith(`${d}/`)) && f.endsWith('.json') && !wanted.has(f));
}
