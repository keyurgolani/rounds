// Renders docs/authority.md from contracts/authority/ and DR-0002. Output
// depends only on those files, never on the scanned code, so a code change
// never forces a regeneration by itself.

import { blockedRows, isNote, pendingByLeaf } from './matrix.mjs';

const cell = (s) => (s === null || s === undefined || s === '' ? '' : String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '));
const code = (s) => (s === null || s === undefined || s === '' ? '' : `\`${String(s).replace(/`/g, "'")}\``);

// The rules the check enforces, in #16's order, then the supporting checks.
export const RULES = [
  ['1', 'A row names more than one target authority, a target names several records, a cache row claims an authority, or two rows claim one authority.', 'AUTH_TWO_AUTHORITIES, AUTH_AUTHORITY_SHARED'],
  ['2', 'A writer of a store that more than one module writes, or a derived consumer, names no conflict of its row that covers it. A conflict exempts only the writers that name it.', 'AUTH_UNFLAGGED_WRITERS'],
  ['3', 'A relation has no owning row.', 'AUTH_RELATION_UNOWNED'],
  ['4', 'A Secret row has a consumer other than a verifier or gateway.', 'AUTH_SECRET_CONSUMER'],
  ['5', 'A row has no disposition, or one that is neither a ledger row nor new-platform-concept:INT-02 or INT-03.', 'AUTH_NO_DISPOSITION'],
  ['6', 'A row names browser storage as its target authority.', 'AUTH_BROWSER_AUTHORITY'],
  ['7', 'A cell is empty, or a leaf ID is not in leaf-ids.json.', 'AUTH_EMPTY_CELL, AUTH_UNRESOLVED_REF'],
  ['8', 'A package, service, or term does not resolve.', 'AUTH_UNRESOLVED_REF, AUTH_PACKAGE_MISMATCH'],
  ['9', 'A baseline-stores.json entry has no row, or a writer names an undeclared store.', 'AUTH_STORE_NO_ROW, AUTH_STORE_UNDECLARED'],
  ['10', 'A Test Definition or Harness Revision row is not server-only.', 'AUTH_CONTAINMENT_VISIBILITY'],
  ['11', 'A changed row keeps its revision or misdeclares its compatibility, or a row is removed.', 'AUTH_REVISION_NOT_BUMPED, AUTH_COMPATIBILITY_UNDECLARED, AUTH_ROW_REMOVED'],
  ['12', 'A command type sits on two rows, or a row lists commands with no command owner.', 'AUTH_COMMAND_DUPLICATE, AUTH_COMMAND_UNOWNED'],
  ['Coverage', 'A collection or browser key family at the audited revision has no baseline-stores.json entry, an entry is not a store there, or a storage call cannot be resolved.', 'AUTH_STORE_UNDECLARED, AUTH_STORE_STALE'],
  ['Conflicts', 'One of #16\'s C1 to C13 is not flagged, or a row and a conflict disagree.', 'AUTH_CONFLICT_MISSING, AUTH_CONFLICT_UNFLAGGED'],
  ['Projections', 'A spec read model has no row, two read models share a projector, or a projection\'s sources and consumers disagree.', 'AUTH_READ_MODEL_MISSING, AUTH_PROJECTION_INCOMPLETE'],
  ['Migration', 'A row with baseline writers has no transfer block.', 'AUTH_TRANSFER_MISSING'],
  ['Privacy', 'An account row has no privacy floor, a platform or pack row has no visibility, or a row lists no public-share entry.', 'AUTH_PRIVACY_MISSING, AUTH_PUBLIC_SHARE_UNDECLARED'],
  ['Citations', 'A citation does not resolve at the audited revision, cites a credential line, or a DR-0002@<n>:<row> example names a missing row or revision.', 'AUTH_CITATION_STALE, AUTH_CITES_SECRET, AUTH_CITATION_UNRESOLVED'],
  ['Secrets', 'An authority file holds a credential value or a secret-shaped string.', 'AUTH_SECRET_VALUE'],
  ['Decisions', 'DR-0002 lacks one of OD-1 to OD-5, or a cell stays blocked on a decision that is no longer open.', 'AUTH_OD_MISSING, AUTH_OD_SETTLED_BLOCKED'],
  ['Labels', 'A row\'s command owner disagrees with its capability\'s owner label, or (with --review) a label is not the catalog owner.', 'AUTH_OWNER_LABEL_MISMATCH, AUTH_LABELS_PIN'],
  ['Corrections', 'An owner-sentence correction names the wrong rows, label, or owner.', 'AUTH_CORRECTION_INVALID'],
  ['Pins', 'DR-0002 and the matrix disagree on revision, a ratified DR-0002 leaves a governed file unpinned, or (with --review) the spec rows or ledger differ from rounds-review.', 'AUTH_REVISION_MISMATCH, AUTH_APPROVAL_INCOMPLETE, AUTH_SPEC_ROW_CHANGED, AUTH_LEDGER_PIN'],
];

export function renderAuthorityMd(A) {
  const m = A.matrix;
  const dr = A.dr;
  const record = `DR-0002@${m.revision}`;
  const issue = (leaf) => (A.leafIssue.get(String(leaf).split('/')[0]) ? `#${A.leafIssue.get(String(leaf).split('/')[0])} (${leaf})` : String(leaf));
  const service = (id) => A.packageList.find((p) => p.id === id)?.service || id;
  const value = (v) => (isNote(v) ? code(v) : cell(v));
  const out = [];
  const p = (...lines) => out.push(...lines);
  const status = dr?.status === 'ratified' ? `ratified in PR #${dr.approvalRef?.pr}` : `${dr?.status ?? 'missing'}, so no row is citable yet`;

  p('# Source-of-Truth and Package-Boundary Matrix', '');
  p('<!-- @generated by `node scripts/conformance/run.mjs --write` from contracts/authority/. Do not edit by hand. -->', '');
  p(`Matrix revision ${m.revision} (\`${record}\`), ${m.compatibility}. The decision record [\`DR-0002\`](decisions/DR-0002-authority-matrix.json) is ${status}. [\`contracts/authority/matrix.json\`](../contracts/authority/matrix.json) gives every durable concept and relation one command owner, one target authority, its read projections, a privacy floor or visibility, a package, a disposition, and a transfer. Code citations are lines at \`${m.auditedRevision}\`; spec lines are in rounds-review \`${m.spec?.source?.replace(/^rounds-review /, '')}\`.`, '');

  p('## Using It', '');
  p(`- Before you write a store, find its row here or in [\`baseline-stores.json\`](../contracts/authority/baseline-stores.json), and write only through that row's command owner. Cite the row in your leaf's \`consumes\` as \`DR-0002@<revision>:<row-id>\`, for example \`${record}:appearance\`.`);
  p('- A cell holds a value, `pending:<leaf-id>` (that leaf fills it; the row is citable and stays closed to implementation until then), `n/a:<reason>`, or `blocked:OD-<n>` (an open owner decision; the row is not citable, and the cell holds only its row).');
  p('- A row has one writable authority at any revision: its legacy writer until the transfer leaf switches it, then the target. Compatibility adapters read, shadow, or compare, never write (spec 2641-2644). Browser storage holds only account-namespaced preferences, drafts, and caches that yield to the server (spec 2005-2007).');
  p('- To change a row, edit `matrix.json`, give the row the new matrix revision and its `compatibility`, raise `revision` in the matrix and in DR-0002, regenerate, and get the record re-approved (its `approvalRef` pins the SHA-256 of `matrix.json`, `packages.json`, `owner-labels.json`, and `baseline-stores.json`). Changing a row\'s command owner, target authority, privacy floor or visibility, scope, or package is breaking, and only that row\'s citers re-cite. Filling a pending cell or adding a row is additive. A store\'s `rows` in `baseline-stores.json` count too: adding one is additive and dropping one is breaking. Rows are superseded, never deleted.');
  p('- #155 (ROUNDS-32-L01) maps every store, field, and key to a row, and #18 (ROUNDS-02-L01) assigns each row its storage. #72 (ROUNDS-14-L01) owns privacy classes, sink policy, and the field map, which only tightens a floor; loosening one needs a breaking revision.');
  p('- Check with `node scripts/conformance/run.mjs` and `node --test scripts/conformance` (Node 22, no install). `--review <rounds-review>` also checks the spec rows verbatim, the ledger pin, and the owner labels against the catalog. `--write` regenerates this file and `baseline-stores.json`, keeping each store\'s rows and note.', '');

  p('## Checks', '');
  p('| Rule | Fails when | Codes |', '| --- | --- | --- |');
  for (const [rule, when, codes] of RULES) p(`| ${rule} | ${cell(when)} | ${codes.split(', ').map(code).join(', ')} |`);
  p('');

  p('## Open Decisions', '');
  p('| Decision | State | Default or basis | Blocked rows |', '| --- | --- | --- | --- |');
  const blocked = blockedRows(A);
  for (const id of ['OD-1', 'OD-2', 'OD-3', 'OD-4', 'OD-5']) {
    const d = A.decisions.get(id);
    const od = d?.od || {};
    const rows = blocked.filter((b) => b.ods.includes(id)).map((b) => code(b.row));
    p(`| ${id}: ${cell(d?.title)} | ${cell(od.state)} | ${cell(od.basis || od.default || '')} | ${rows.join(', ') || 'none'} |`);
  }
  p('');

  p('## Rows', '');
  p('Status: `citable`, `citable, N pending` (closed to implementation until those cells fill), or `blocked` on an open decision.', '');
  const pending = (r) => {
    let n = 0;
    const visit = (v) => {
      if (typeof v === 'string') { if (v.startsWith('pending:')) n++; return; }
      if (Array.isArray(v)) v.forEach(visit);
      else if (v && typeof v === 'object') Object.values(v).forEach(visit);
    };
    visit(r);
    return n;
  };
  const scopes = [['account', 'Account'], ['platform-global', 'Platform-global'], ['pack-owned', 'Pack-owned']];
  for (const [scope, title] of scopes) {
    const rows = A.rows.filter((r) => r.scope === scope);
    if (!rows.length) continue;
    p(`### ${title}`, '');
    p('| Row | Concept | Command owner | Target authority | Floor or visibility | Package | Disposition | Conflicts | Transfer | Status |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const r of rows) {
      const concept = (r.spec || r.summary || {}).information;
      const owner = r.command_owner && typeof r.command_owner === 'object' ? `${issue(r.command_owner.leaf)}, ${isNote(r.command_owner.service) ? code(r.command_owner.service) : cell(service(r.command_owner.service))}` : value(r.command_owner);
      const target = (r.target_authority && typeof r.target_authority === 'object' && !Array.isArray(r.target_authority) ? `${cell(r.target_authority.record)} (${r.target_authority.location})` : value(r.target_authority)) + (r.yields_to ? `; yields to ${code(r.yields_to)}` : '');
      const spec = r.spec ? ` (spec ${r.spec.line}${r.split ? `; this part: ${cell(r.split)}` : ''})` : '';
      const ods = blocked.find((b) => b.row === r.id)?.ods;
      const n = pending(r);
      const st = ods ? `blocked: ${ods.join(', ')}` : n ? `citable, ${n} pending` : 'citable';
      p(`| ${code(r.id)} | ${cell(concept)}${spec} | ${owner} | ${target} | ${cell(r.privacy_floor || r.visibility)} | ${value(r.package)} | ${code(r.disposition)} | ${(r.conflicts || []).join(', ')} | ${r.transfer ? issue(r.transfer.leaf) : ''} | ${st} |`);
    }
    p('');
  }

  p('## Baseline Conflicts', '');
  p(`Second writers and split authorities at \`${m.auditedRevision}\`. C1 to C13 come from #16; the rest were found while building the matrix.`, '');
  p('| ID | Conflict | Rows | Disposition | Resolving leaves |', '| --- | --- | --- | --- | --- |');
  for (const c of A.conflicts) {
    const blockedBy = c.blockedBy ? ` Blocked on ${c.blockedBy}.` : '';
    p(`| ${c.id} | ${cell(c.title)}.${blockedBy} | ${(c.rows || []).map(code).join(', ')} | ${code(c.disposition)} | ${(c.resolvingLeaves || []).map(issue).join(', ')} |`);
  }
  p('');

  p('## Read Models', '');
  p('Each spec read model (spec 1970-1980) has one projector. Every projection carries its source change-set watermark and stale and degraded behavior; #23 (ROUNDS-02-L06) and #146 (ROUNDS-31-L01) enforce them at runtime.', '');
  p('| Read model | Row | Projector | Sources |', '| --- | --- | --- | --- |');
  for (const x of A.readModels) {
    const r = A.row(x.row);
    p(`| ${cell(x.name)} | ${code(x.row)} | ${r?.projection ? issue(r.projection.projector) : ''} | ${(r?.projection?.sources || []).map(code).join(', ')} |`);
  }
  p('');

  p('## Relations', '');
  p('| Relation | From | To | Owning row |', '| --- | --- | --- | --- |');
  for (const rel of A.relations) p(`| ${code(rel.id)} | ${code(rel.from)} | ${code(rel.to)} | ${code(rel.owner_row)} |`);
  p('');

  p('## Packages', '');
  const added = A.packageList.filter((x) => x.decision);
  p(`One package per spec service (spec 1919-1935)${added.length ? `, plus ${added.map((x) => `${x.service} (DR-0002 ${x.decision})`).join(', ')}` : ''}. #18 (ROUNDS-02-L01) sets each \`target_path\`.`, '');
  p('| Package | Service | Spec | Baseline locations |', '| --- | --- | --- | --- |');
  for (const pkg of A.packageList) {
    const locs = Array.isArray(pkg.baseline_locations) ? pkg.baseline_locations.map(code).join(', ') : code(pkg.baseline_locations);
    p(`| ${code(pkg.id)} | ${cell(pkg.service)} | ${cell(pkg.spec)}${pkg.decision ? ` (DR-0002 ${pkg.decision})` : ''} | ${locs} |`);
  }
  p('');

  p('## Owner Labels', '');
  p('Each capability\'s owner label maps to one service, `none` (the label owns no commands), `blocked:OD-<n>`, or `per-row`. A row whose command owner is one of the capability\'s leaves takes that service.', '');
  p('| Capability | Label | Service |', '| --- | --- | --- |');
  for (const l of A.labelList) {
    const rows = l.rows && typeof l.rows === 'object' ? Object.entries(l.rows).map(([id, s]) => `${code(id)} to ${code(s)}`).join(', ') : '';
    const svc = l.service === 'per-row' ? `per-row: ${rows}` : `${code(l.service)}${rows ? `, except ${rows}` : ''}`;
    p(`| ${l.capability} | ${cell(l.label)} | ${svc} |`);
  }
  p('');

  p('## Pending Cells', '');
  p('| Leaf | Cells | Rows |', '| --- | --- | --- |');
  const byLeaf = [...pendingByLeaf(A).entries()].sort(([a, x], [b, y]) => y.cells - x.cells || a.localeCompare(b));
  for (const [leaf, info] of byLeaf) p(`| ${issue(leaf)} | ${info.cells} | ${info.rows.size} |`);
  p('');
  return `${out.join('\n')}`.replace(/\n+$/, '\n');
}
