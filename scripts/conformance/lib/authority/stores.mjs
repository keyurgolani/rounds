// Baseline stores (ROUNDS-01-L02): every PocketBase collection live at the
// audited revision and every browser storage key family frontend/src wrote
// there, including the PocketBase SDK's default auth store. The list is
// generated from that pinned tree; each entry's `rows` (the DR-0002 rows it
// belongs to) is the part a person writes, and regeneration keeps it.
//
// #155 (ROUNDS-32-L01) seeds its store registry from this file and repoints
// rule 9 at that registry.

import { extractCollections } from '../vocabulary/coverage.mjs';
import { extractBrowserKeys } from './browser-keys.mjs';

export const BASELINE_STORES_PATH = 'contracts/authority/baseline-stores.json';

// Non-literal collection sites (the exp_* junctions) resolve through the
// vocabulary's collection adapter entries, as #15's coverage does.
function nonLiteralResolver(adapters) {
  return (ev) => {
    const names = (adapters || []).filter((a) => a.kind === 'collection' && a.source?.path === ev.path && String(a.source.lines || '').split(',').some((part) => {
      const [x, y] = part.split('-').map(Number);
      return ev.line >= x && ev.line <= (Number.isInteger(y) ? y : x);
    })).map((a) => a.legacyName);
    return names.length ? [...new Set(names)] : null;
  };
}

// Returns { ok, stores: [{ id, kind, name, ... }], purgeSites, unresolved } for the tree.
export function extractBaselineStores(tree, vocabularyAdapters) {
  const collections = extractCollections(tree, nonLiteralResolver(vocabularyAdapters));
  const keys = extractBrowserKeys(tree);
  const stores = [];
  for (const c of collections.items) {
    if (c.historical) continue;
    stores.push({ id: `collection:${c.name}`, kind: 'collection', name: c.name, created: `${c.path}:${c.line}` });
  }
  for (const [family, f] of keys.families) {
    stores.push({ id: `browser-key:${family}`, kind: 'browser-key', name: family, api: f.api, writes: f.writes, reads: f.reads });
  }
  return {
    stores,
    purgeSites: keys.purges,
    unresolved: [...keys.unresolved, ...collections.unresolved.map((ev) => `${ev.path}:${ev.line}`)],
  };
}

// Merges the human-written `rows` and `note` of an existing file into the
// extracted list, so regeneration only changes what extraction changed.
export function baselineStoresDocument(extracted, previous, auditedRevision) {
  const kept = new Map((previous?.stores || []).map((s) => [s.id, s]));
  const stores = extracted.stores.map((s) => {
    const old = kept.get(s.id);
    const out = { ...s, rows: Array.isArray(old?.rows) ? old.rows : [] };
    if (old?.note) out.note = old.note;
    return out;
  });
  const collections = stores.filter((s) => s.kind === 'collection').length;
  return {
    $schema: './baseline-stores.schema.json',
    registry: 'rounds-baseline-stores',
    description: 'Generated by node scripts/conformance/run.mjs --write from the audited revision: every live PocketBase collection and every browser storage key family frontend/src writes or reads there. Only rows and note are written by hand; regeneration keeps them. #155 (ROUNDS-32-L01) seeds its store registry from this file.',
    auditedRevision,
    counts: { collections, browserKeyFamilies: stores.length - collections },
    purgeSites: extracted.purgeSites,
    stores,
  };
}
