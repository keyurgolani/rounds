export function renderLabelsTs(terms) {
  const all = terms.terms || [];
  const userFacing = all.filter((t) => t.visibility === 'user-facing' && t.label);
  const inspection = all.filter((t) => t.visibility === 'inspection-only');
  const record = `${terms.decisionRecord}@${terms.revision}`;
  const out = [];
  out.push('// @generated by `node scripts/conformance/run.mjs --write` from contracts/vocabulary/terms.json.');
  out.push('// Do not edit by hand: change the registry and regenerate. See docs/vocabulary.md.');
  out.push('');
  out.push(`/** Registry revision. vocabulary@${terms.revision} is ${record}; cite it in a leaf's consumes. */`);
  out.push(`export const VOCABULARY_REVISION = ${terms.revision};`);
  out.push(`export const VOCABULARY_RECORD = ${q(record)};`);
  out.push('');
  out.push('type Forms = readonly [singular: string, plural: string];');
  out.push('type LabelEntry = { readonly default: string; readonly options: Readonly<Record<string, Forms>> };');
  out.push('');
  out.push('const LABELS = {');
  for (const t of userFacing) {
    const opts = t.label.options.map((o) => `${q(o.key)}: [${q(o.singular)}, ${q(o.plural)}]`).join(', ');
    out.push(`  ${q(t.id)}: { default: ${q(t.label.default)}, options: { ${opts} } },`);
  }
  out.push('} as const;');
  out.push('');
  out.push('/** A user-facing term. Internal and inspection-only terms are not TermIds and have no label. */');
  out.push('export type TermId = keyof typeof LABELS;');
  out.push("export type LabelOption<T extends TermId> = Extract<keyof (typeof LABELS)[T]['options'], string>;");
  out.push('');
  out.push('export interface LabelOptions<T extends TermId> {');
  out.push('  /** Label option for terms labeled by stage, kind, or submission state. Defaults to the term\'s default option. */');
  out.push('  option?: LabelOption<T>;');
  out.push('  /** Returns the plural form when set and not 1. */');
  out.push('  count?: number;');
  out.push('}');
  out.push('');
  out.push('/** The user-facing label of a term. Throws for an unknown or non-user-facing term: there is no internal-term fallback. */');
  out.push('export function label<T extends TermId>(termId: T, opts: LabelOptions<T> = {}): string {');
  out.push('  const entry = (LABELS as Readonly<Record<string, LabelEntry>>)[termId];');
  out.push('  if (!entry) throw new Error(`No user-facing label for "${String(termId)}"`);');
  out.push('  const key: string = opts.option ?? entry.default;');
  out.push('  const forms = entry.options[key];');
  out.push('  if (!forms) throw new Error(`"${termId}" has no label option "${key}"`);');
  out.push('  return opts.count === undefined || opts.count === 1 ? forms[0] : forms[1];');
  out.push('}');
  out.push('');
  out.push('/** How a surface picks the option for terms whose label varies (spec 1004, 1005, 1006, 1011), and the leaf that owns the mapping. */');
  out.push('export const labelAxes = {');
  for (const t of userFacing.filter((x) => x.label.axis !== 'none')) {
    const owners = t.label.mappingOwner ? `[${t.label.mappingOwner.map(q).join(', ')}]` : '[]';
    out.push(`  ${q(t.id)}: { axis: ${q(t.label.axis)}, mappingOwner: ${owners} },`);
  }
  out.push('} as const;');
  out.push('');
  out.push('/** Technical names for history, provenance, and advanced inspection surfaces only (spec 1016-1017). */');
  out.push('export const inspectionTerms = {');
  for (const t of inspection) out.push(`  ${q(t.id)}: ${q(t.term)},`);
  out.push('} as const;');
  out.push('export type InspectionTermId = keyof typeof inspectionTerms;');
  out.push('');
  out.push('/** The spec 1000-1014 default user-facing labels, as written. */');
  out.push('export const specLabels = {');
  for (const t of userFacing.filter((x) => x.label.specLabel && /^spec 10(0\d|1[0-4])$/.test(x.label.basis))) out.push(`  ${q(t.id)}: ${q(t.label.specLabel)},`);
  out.push('} as const;');
  out.push('');
  return out.join('\n');
}

