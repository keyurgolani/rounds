// Renders the generated vocabulary files from contracts/vocabulary/ and DR-0001.
// Output depends only on those files, never on the scanned code, so a code
// change never forces a regeneration by itself.

export const LABELS_TS = 'frontend/src/vocabulary/labels.ts';
export const VOCABULARY_MD = 'docs/vocabulary.md';
export const CORRECTIONS_MD = 'docs/decisions/DR-0001-owner-corrections.md';

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const cell = (s) => (s === null || s === undefined || s === '' ? '' : String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '));
const code = (s) => (s === null || s === undefined || s === '' ? '' : `\`${String(s).replace(/`/g, "'")}\``);

function leafLabel(leafIds, ref) {
  if (!ref) return '';
  const id = String(ref).split('/')[0];
  const leaf = (leafIds?.leaves || []).find((l) => l.id === id);
  return leaf?.issue ? `#${leaf.issue} (${ref})` : String(ref);
}

