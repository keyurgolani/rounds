export function renderVocabularyMd(terms, adapters, leafIds, dr) {
  const record = `${terms.decisionRecord}@${terms.revision}`;
  const all = terms.terms || [];
  const out = [];
  const p = (...lines) => out.push(...lines);
  p('# Product Vocabulary', '');
  p('<!-- @generated by `node scripts/conformance/run.mjs --write` from contracts/vocabulary/. Do not edit by hand. -->', '');
  p(`Registry revision ${terms.revision} (\`vocabulary@${terms.revision}\`, which is \`${record}\`), ${terms.compatibility}. The decision record is [\`${terms.decisionRecord}\`](decisions/${terms.decisionRecord}-product-vocabulary.json); owner items are in [\`${terms.decisionRecord}-owner-corrections.md\`](decisions/${terms.decisionRecord}-owner-corrections.md).`, '');
  p('Every name a user sees and every domain term an implementer uses comes from [`contracts/vocabulary/terms.json`](../contracts/vocabulary/terms.json). A baseline name that differs has an entry in [`adapters.json`](../contracts/vocabulary/adapters.json) naming the leaf that retires it. [`leaf-ids.json`](../contracts/vocabulary/leaf-ids.json) lists every leaf ID a file may cite.', '');
  p('## Using It', '');
  p("- UI code takes user-visible names from `frontend/src/vocabulary/labels.ts`. `label('extracted-claim')` returns \"Proposed change\", and `label('pursuit', { option: 'pipeline-item', count: 2 })` returns \"Pipeline items\". Internal and inspection-only terms have no label; history, provenance, and inspection surfaces use `inspectionTerms`.");
  p(`- A leaf that depends on these names cites \`${record}\` in its \`consumes\`.`);
  p('- Existing copy keeps its adapter entry until its retiring leaf replaces it. Remove the entry in that PR.');
  p(`- To change a term, edit \`terms.json\`, raise \`revision\` there and in \`${terms.decisionRecord}\`, mark \`compatibility\` additive or breaking, regenerate, and get the record re-approved (its \`approvalRef\` pins the file's SHA-256). A breaking revision keeps a \`term\` adapter entry for each removed name.`);
  p('- A new name in the coverage set needs a term label or an adapter entry. Never loosen the rule.');
  p('- Check with `node scripts/conformance/run.mjs` and `node --test scripts/conformance` (Node 22, no install). `--write` regenerates this file, `labels.ts`, and the owner corrections file. CI runs both in the `conformance` job.', '');
  p('## Positioning', '');
  p(`> ${terms.positioning.statement}`, '');
  p(`Title form: ${terms.positioning.title}. Source: ${terms.positioning.source} (decision P1).`, '');
  p('## Terms', '');
  p('Visibility: `user-facing` terms have a label; `inspection-only` terms appear only on history, provenance, and inspection surfaces (spec 1016-1017); `internal` terms never appear in the UI. A term marked ratified-here, or a label marked [G6] to [G9], comes from a decision beyond spec text and is pending owner approval. The default option is bold when a term has several.', '');
  for (const cat of terms.categories) {
    const inCat = all.filter((t) => t.category === cat.id);
    p(`### ${cat.name}`, '');
    p('| Term | ID | Label | Visibility | Owning leaf | Source |', '| --- | --- | --- | --- | --- | --- |');
    for (const t of inCat) {
      const lbl = t.label ? t.label.options.map((o) => (o.key === t.label.default && t.label.options.length > 1 ? `**${o.singular}**` : o.singular)).join(', ') : '';
      const here = t.label && /^G[6-9]\b/.test(t.label.basis) ? ` [${t.label.basis.split(' ')[0]}]` : '';
      const axis = (t.label && t.label.axis !== 'none' ? ` (by ${t.label.axis})` : '') + here;
      const ns = t.namespace === 'platform' ? '' : ` \`${t.namespace}\``;
      const status = t.status === 'ratified-here' ? ' (ratified-here)' : '';
      p(`| ${cell(t.term)}${ns} | ${code(t.id)} | ${cell(lbl + axis)} | ${t.visibility}${status} | ${leafLabel(leafIds, t.owningLeaf)} | ${cell(t.source)} |`);
    }
    p('');
    for (const t of inCat) {
      const extra = [];
      if (t.aliases?.length) extra.push(`Aliases: ${t.aliases.map((a) => `"${a}"`).join(', ')}.`);
      if (t.definedBy?.length) extra.push(`Defined by ${t.definedBy.map((d) => leafLabel(leafIds, d)).join(', ')}.`);
      if (t.label?.specLabel && t.label.specLabel !== t.label.options[0].singular) extra.push(`Spec label: "${t.label.specLabel}".`);
      p(`- **${t.term}** (${code(t.id)}): ${t.definition || ''}${extra.length ? ` ${extra.join(' ')}` : ''}`);
    }
    p('');
  }
  p('## Shared Labels', '');
  for (const s of terms.sharedLabels) p(`- "${s.label}": ${s.terms.map(code).join(' and ')} (${s.cites.join(', ')}; ${s.decision}${s.specChangeRequest ? `, ${s.specChangeRequest}` : ''}).`);
  p('');
  p('## Usage Rules', '');
  for (const r of terms.usageRules) p(`- ${r.decision}: ${r.rule}`);
  p('- G7: In "X or Y", the first name is canonical and the second is a label option.', '');
  p('## Namespaces', '');
  for (const n of terms.namespaces) p(`- ${code(n.id)}${n.status ? ` (${n.status})` : ''}: ${n.description}`);
  p('');
  p(`Platform core (${terms.platformCore.source}): ${terms.platformCore.names.map((n) => n.name).join(', ')}. No pack term, alias, or label may equal one of these or a platform term.`, '');
  p('## Dispositions', '');
  p(`Features (${terms.dispositions.feature.source}, ${terms.dispositions.decision}). ${terms.dispositions.feature.qualifier}`, '');
  for (const v of terms.dispositions.feature.values) p(`- \`${v.value}\`: ${v.meaning}`);
  p('', `Data items (${terms.dispositions.item.source}):`, '');
  for (const v of terms.dispositions.item.values) p(`- \`${v.value}\`: ${v.meaning}`);
  p('', `Catalog words: ${terms.dispositions.item.catalogWords.map((w) => `${w.word} is \`${w.value}\`${w.condition ? ` ${w.condition}` : ''}`).join('; ')}.`, '');
  p('## Data-Preserving Clean Cutover', '');
  p(`${terms.cutover.definition} (${terms.cutover.source}, ${terms.cutover.decision})`, '');
  p(`Write it as "${terms.cutover.term.toLowerCase()}". The check rejects the phrase without "data-preserving" anywhere in the repository except these shipped migration lines, which are never edited: ${terms.cutover.allowlist.map((a) => code(`${a.path}:${a.line}`)).join(', ')}.`, '');
  p('## Adapters', '');
  const list = adapters?.adapters || [];
  const kinds = [...new Set(list.map((a) => a.kind))];
  p(`${list.length} entries: ${kinds.map((k) => `${list.filter((a) => a.kind === k).length} ${k}`).join(', ')}. Each maps a baseline name to a term or to the leaf that decides it, gives the label it becomes, and names the retiring leaf: the leaf that renames or removes the name, or confirms it as a canonical internal name.`, '');
  for (const k of kinds) {
    p(`### ${k}`, '');
    p('| Legacy name | Where | Term or decided by | Target label | Retiring leaf |', '| --- | --- | --- | --- | --- |');
    for (const a of list.filter((x) => x.kind === k)) {
      const name = `${a.field ? `${a.field}: ` : ''}${a.prop ? `${a.prop}: ` : ''}${a.legacyName}${a.historical ? ' (historical)' : ''}`;
      const where = `${a.source.path}${a.source.lines ? `:${a.source.lines}` : ''}${a.source.revision ? `@${a.source.revision}` : ''}`;
      const termOrLeaf = a.termId ? code(a.termId) : `decided by ${leafLabel(leafIds, a.decidedBy)}`;
      p(`| ${cell(name)} | ${code(where)} | ${termOrLeaf} | ${cell(a.targetLabel)} | ${leafLabel(leafIds, a.retiringLeaf)} |`);
    }
    p('');
  }
  p('## Coverage Set', '');
  p('The check extracts these names from the repository and maps each to a term label or an adapter entry:', '');
  p('- `collection`: PocketBase collections created or dropped by `up` migrations in `pocketbase/pb_migrations/`, plus the built-in `users`. Dropped ones are historical. A non-literal name needs adapter entries whose `source.lines` cover the call. #155 (ROUNDS-32-L01) takes this over once its store registry lands.');
  p('- `stored-value`: `user_progress.question_type` and `user_progress.status` select values, and the `INTERVIEW_TYPES` keys (and aliases) stored in `interview_rounds.round_type`.');
  p('- `api-route`: the prefix of each router `backend/main.py` mounts, and its direct routes such as `/health`.');
  p('- `route-segment`: literal path segments of `<Route path>` and `<Navigate to>` in `frontend/src/App.tsx`.');
  p('- `ui-string`: navigation labels, user-menu destinations, and sidebar headings in `Layout.tsx`, and each Command Center entry\'s label and description in `command-center/registry.tsx`.');
  p('- `app-header`: literal `eyebrow` and `title` props at every `<AppHeader>` call site under `frontend/src`.');
  p('- `positioning`: `README.md` lines 1 and 3, `docs/architecture.md` line 3, `frontend/index.html` line 17, `Login.tsx` line 239, and `SHOWCASE.md` line 3.', '');
  p('UI strings and AppHeader props that equal a term\'s label are covered by the term; everything else needs an adapter entry.', '');
  p('## Leaf IDs', '');
  const leaves = leafIds?.leaves || [];
  const filed = leaves.filter((l) => l.status === 'filed');
  const proposed = leaves.filter((l) => l.status === 'proposed');
  const rejected = leaves.filter((l) => l.status === 'rejected');
  p(`${filed.length} filed leaves (#1 to #${filed.length} in catalog order), pinned to ${leafIds?.catalog?.source} sha256 \`${leafIds?.catalog?.sha256}\`. ${proposed.length} proposed: ${proposed.map((l) => `#${l.issue} ${l.id}`).join(', ')}. ${rejected.length} rejected (folded): ${rejected.map((l) => `${l.id} into ${leafLabel(leafIds, l.foldedInto)}`).join(', ')}. A \`<leaf-id>/<stage>\` reference resolves on the leaf part. Verify the pin with \`node scripts/conformance/run.mjs --catalog <path to capabilities.json>\`.`, '');
  p('## Decisions', '');
  for (const d of dr?.decisions || []) p(`- **${d.id}. ${d.title}** (${d.status}). ${d.decision}`);
  p('');
  p('## Check Codes', '');
  p('| Code | Meaning |', '| --- | --- |');
  for (const [c, m] of CODES) p(`| ${code(c)} | ${cell(m)} |`);
  p('');
  return out.join('\n');
}

// ------------------------------------------------- owner corrections file

export function renderCorrectionsMd(terms, leafIds, dr) {
  const record = `${dr.id}@${dr.revision}`;
  const out = [];
  const p = (...lines) => out.push(...lines);
  const cited = (item) => (item.citedBy?.length ? ` Cited by ${item.citedBy.map((c) => leafLabel(leafIds, c)).join(', ')}.` : '');
  p(`# ${dr.id} Owner Corrections`, '');
  p('<!-- @generated by `node scripts/conformance/run.mjs --write` from the decision record. Do not edit by hand. -->', '');
  p(`Items in \`${record}\`, from ${leafLabel(leafIds, dr.leaf)}, that need the owner: catalog corrections for re-authorization, decisions made beyond spec text, spec-change requests, and departures from the spec or the filed body. #17's re-authorization imports this file (its item 7).`, '');
  p('## Corrections for Owner Re-authorization', '');
  (dr.corrections || []).forEach((c, i) => p(`${i + 1}. **${c.id}. ${c.title}.** ${c.detail}${cited(c)}`));
  p('');
  p('## Decisions Ratified Here', '');
  p('These go beyond spec text. Approve or change each; a change becomes a superseding revision.', '');
  for (const d of (dr.decisions || []).filter((x) => x.status === 'ratified-here')) p(`- **${d.id}. ${d.title}.** ${d.decision}`);
  p('');
  const hereTerms = (terms.terms || []).filter((t) => t.status === 'ratified-here');
  if (hereTerms.length) p(`Terms that follow from them: ${hereTerms.map((t) => `${t.term} (\`${t.id}\`)`).join(', ')}.`, '');
  p('## Spec-Change Requests', '');
  for (const s of dr.specChangeRequests || []) p(`- **${s.id}. ${s.title}.** ${s.detail}${cited(s)}`);
  p('');
  p('## Departures', '');
  for (const s of dr.departures || []) p(`- **${s.id}. ${s.title}.** ${s.detail}${cited(s)}`);
  p('');
  p('## Containment Terms', '');
  const g12 = (dr.decisions || []).find((d) => d.id === 'G12');
  if (g12) p(g12.decision, '');
  p('| Term | ID | Owning leaf | Source |', '| --- | --- | --- | --- |');
  for (const id of ['legacy-artifact-snapshot', 'test-definition', 'harness-revision', 'artifact-renderer-contract', 'share-capability']) {
    const t = (terms.terms || []).find((x) => x.id === id);
    if (t) p(`| ${cell(t.term)} | ${code(t.id)} | ${leafLabel(leafIds, t.owningLeaf)} | ${cell(t.source)} |`);
  }
  p('');
  return out.join('\n');
}
