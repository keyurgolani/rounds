-- Practice status per user per question. Replaces the client-side
-- `rounds.practiceStatus.v1` localStorage store.
create table if not exists public.user_progress (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references auth.users(id) on delete cascade,
  question_type  text not null check (question_type in ('system', 'coding', 'behavioral')),
  question_id    bigint not null,
  status         text default 'todo' check (status in ('todo', 'in-progress', 'mastered')),
  notes          text default '',
  confidence     double precision default 0,
  completed_at   timestamptz,
  updated_at     timestamptz default now(),
  unique (user_id, question_type, question_id)
);
create index if not exists user_progress_user_id_idx on public.user_progress (user_id);

-- Optional: server-synced preferences (theme, accent, density, etc.).
-- For now the app keeps these in localStorage; this table exists so we can
-- sync later without another migration.
create table if not exists public.user_preferences (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  theme       text default 'light',
  accent      text default 'terracotta',
  type_variant text default 'serif-display',
  density     text default 'comfortable',
  nav_style   text default 'sidebar',
  card_treatment text default 'layered',
  updated_at  timestamptz default now()
);

-- Per-user, per-question, per-language code drafts. Synced from the Monaco
-- editor on a 10-second cadence; localStorage is the fast path.
create table if not exists public.code_drafts (
  user_id     uuid not null references auth.users(id) on delete cascade,
  question_id bigint not null,
  language    text not null,
  code        text not null,
  updated_at  timestamptz default now(),
  primary key (user_id, question_id, language)
);

create index if not exists code_drafts_user_id_idx on public.code_drafts (user_id);

-- Trigger: bump updated_at on user-scoped tables ---------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

