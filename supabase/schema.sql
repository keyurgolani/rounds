-- ==========================================================================
-- Rounds — Supabase schema
-- ==========================================================================
-- Apply via the Supabase SQL Editor or `supabase db push`. Runs idempotently:
-- tables use CREATE TABLE IF NOT EXISTS; policies drop before recreate.
--
-- Identity model
-- --------------
-- Authenticated users live in `auth.users` (managed by Supabase). Rows in
-- the user-scoped tables carry `user_id uuid` referencing `auth.users(id)`
-- with ON DELETE CASCADE. Row-level security is ON for every user-scoped
-- table; the only policy allows `auth.uid() = user_id`.
--
-- Content tables (questions, categories) are shared across all users and
-- are readable by any authenticated user but writable only by the service
-- role (seeding + admin).
-- ==========================================================================

